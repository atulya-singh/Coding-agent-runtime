"""Collect what the agent changed, as a patch, and replay it onto a clean tree.

The patch is the unit of record for Phase 4. Grading the container the agent
worked in would grade an environment as much as a change: setup installed
packages, tests wrote caches, a stray `pip install` may have papered over the real
problem. Grading a patch applied to a pristine export of the base commit means the
result depends on exactly one thing -- the diff -- and that diff is a durable,
reviewable, re-runnable artifact (Principle 3: a result should be reproducible).

Everything here is host-side file and git work; no agent code is executed. The
repository the diff is taken against never contains a `.git` directory, and the
container never needs git installed, which keeps this consistent with how
`Tasks.verify` handles the same problem.
"""
from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import List, Optional, Sequence

#: Generated by setup and by running tests, not by the agent. Left in, they would
#: swamp the diff (`pip install -e .` alone writes a whole *.egg-info tree) and
#: make an otherwise-identical run produce a different patch each time. Matched on
#: basename, the way .gitignore-style tooling does it.
DEFAULT_EXCLUDES: Sequence[str] = (
    ".git",
    "__pycache__",
    "*.pyc",
    "*.pyo",
    "*.so",
    "*.egg-info",
    ".eggs",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    ".tox",
    ".coverage",
    ".coverage.*",
    "build",
    "dist",
)

#: A patch far larger than any real change is more likely a vendored dependency,
#: a committed virtualenv or a loop that wrote the same file a thousand times.
#: Refuse it rather than spend a container on it.
MAX_PATCH_BYTES = 5 * 1024 * 1024

_DIFF_HEADER = re.compile(r"^diff --git a/(.+?) b/(.+)$", re.MULTILINE)


class PatchError(Exception):
    """A patch could not be built, is unsafe, or does not apply."""


@dataclass
class Patch:
    text: str
    files: List[str] = field(default_factory=list)
    lines_added: int = 0
    lines_deleted: int = 0

    @property
    def is_empty(self) -> bool:
        return not self.text.strip()

    @property
    def sha256(self) -> str:
        """Identity of the change, for the result record."""
        return hashlib.sha256(self.text.encode("utf-8")).hexdigest()

    @property
    def size_bytes(self) -> int:
        return len(self.text.encode("utf-8"))

    @classmethod
    def from_text(cls, text: str) -> "Patch":
        paths: List[str] = []
        for old, new in _DIFF_HEADER.findall(text):
            for path in (old, new):
                # /dev/null appears as the counterpart for adds and deletes.
                if path != "/dev/null" and path not in paths:
                    paths.append(path)

        added = deleted = 0
        for line in text.splitlines():
            if line.startswith("+") and not line.startswith("+++"):
                added += 1
            elif line.startswith("-") and not line.startswith("---"):
                deleted += 1

        return cls(text=text, files=sorted(paths), lines_added=added, lines_deleted=deleted)

    @classmethod
    def empty(cls) -> "Patch":
        """The patch an agent that changed nothing produces. Used as the floor in
        self-tests: every task must grade it as unsolved."""
        return cls(text="")

    def to_dict(self) -> dict:
        return {
            "sha256": self.sha256,
            "size_bytes": self.size_bytes,
            "files": self.files,
            "lines_added": self.lines_added,
            "lines_deleted": self.lines_deleted,
            "is_empty": self.is_empty,
        }


# ---- host-side git ---------------------------------------------------------


def _git(repo: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, check=False
    )
    if result.returncode != 0:
        raise PatchError(
            f"git {' '.join(args[:2])} failed: {result.stderr.decode('utf-8', 'replace').strip()}"
        )
    return result.stdout.decode("utf-8", "replace")


def _copy_tree(src: Path, dest: Path, excludes: Sequence[str]) -> None:
    """Copy `src` into an existing or new `dest`, dropping excluded entries.

    Symlinks are copied as symlinks, never followed: following one would let a
    link the agent created pull host files into the diff.
    """
    dest.mkdir(parents=True, exist_ok=True)
    ignore = shutil.ignore_patterns(*excludes)
    for entry in src.iterdir():
        if entry.name in ignore(str(src), [entry.name]):
            continue
        target = dest / entry.name
        if entry.is_symlink():
            target.symlink_to(entry.readlink())
        elif entry.is_dir():
            shutil.copytree(entry, target, symlinks=True, ignore=ignore, dirs_exist_ok=True)
        else:
            shutil.copy2(entry, target)


def diff_trees(
    base_dir: Path,
    candidate_dir: Path,
    excludes: Sequence[str] = DEFAULT_EXCLUDES,
) -> Patch:
    """Diff two plain directories into a `git apply`-able patch.

    Done through a throwaway git repository rather than `diff -ru` so the output
    is a real git patch: it carries mode changes, file adds and deletes, and
    binary hunks, and it applies with the same tool everywhere.
    """
    base_dir, candidate_dir = Path(base_dir), Path(candidate_dir)
    if not base_dir.is_dir():
        raise PatchError(f"base tree does not exist: {base_dir}")
    if not candidate_dir.is_dir():
        raise PatchError(f"candidate tree does not exist: {candidate_dir}")

    scratch = Path(tempfile.mkdtemp(prefix="agent-runtime-diff-"))
    work = scratch / "work"
    try:
        _copy_tree(base_dir, work, excludes)
        _git(work, "init", "--quiet")
        _git(work, "add", "-A")
        # Identity and signing are forced on the command line: the host's global
        # git config must not be able to make this step fail or prompt.
        _git(
            work,
            "-c", "user.email=evaluator@agent-runtime.invalid",
            "-c", "user.name=agent-runtime evaluator",
            "-c", "commit.gpgsign=false",
            "commit", "--quiet", "--allow-empty", "-m", "base",
        )

        for entry in work.iterdir():
            if entry.name == ".git":
                continue
            if entry.is_dir() and not entry.is_symlink():
                shutil.rmtree(entry)
            else:
                entry.unlink()
        _copy_tree(candidate_dir, work, excludes)

        _git(work, "add", "-A")
        text = _git(
            work,
            "diff", "--cached", "--binary", "--no-color", "--no-ext-diff",
            "--src-prefix=a/", "--dst-prefix=b/",
        )
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    patch = Patch.from_text(text)
    if patch.size_bytes > MAX_PATCH_BYTES:
        raise PatchError(
            f"patch is {patch.size_bytes} bytes, over the {MAX_PATCH_BYTES}-byte limit "
            f"({len(patch.files)} files) -- refusing to evaluate it"
        )
    return patch


def collect_patch(sandbox, base_dir: Path, artifacts_dir: Optional[Path] = None) -> Patch:
    """Take the agent's finished container and produce its diff against the base.

    `Sandbox.collect_results` is the existing way out of a container, and it also
    brings the run log with it, so passing `artifacts_dir` keeps the working tree
    and the command history that produced it side by side with the patch.
    """
    holder = artifacts_dir or Path(tempfile.mkdtemp(prefix="agent-runtime-collect-"))
    try:
        collected = sandbox.collect_results(str(holder))
        return diff_trees(Path(base_dir), collected / "repository")
    finally:
        if artifacts_dir is None:
            shutil.rmtree(holder, ignore_errors=True)


# ---- applying --------------------------------------------------------------


def unsafe_paths(patch: Patch) -> List[str]:
    """Paths in the patch that must never be written.

    `git apply` already refuses to escape the tree, but the check is repeated here
    because these paths come from model-driven edits: rejecting them before the
    patch reaches any tool means an escape attempt is a recorded evaluation
    finding rather than something caught silently one layer down.
    """
    bad = []
    for path in patch.files:
        pure = PurePosixPath(path)
        if pure.is_absolute() or ".." in pure.parts or path.startswith("~"):
            bad.append(path)
        elif pure.parts and pure.parts[0] == ".git":
            # The clean tree is not a git repo, but the diff step makes one; a
            # planted hook would run there.
            bad.append(path)
    return bad


def apply_patch(patch: Patch, dest_dir: Path) -> None:
    """Apply `patch` to a clean checkout. Raises PatchError if it does not apply.

    A patch that does not apply is an agent failure, not an infrastructure one:
    it means the change was described against a tree that no longer exists.
    """
    dest_dir = Path(dest_dir)
    if patch.is_empty:
        return

    bad = unsafe_paths(patch)
    if bad:
        raise PatchError(f"patch writes outside the repository: {', '.join(bad)}")
    if patch.size_bytes > MAX_PATCH_BYTES:
        raise PatchError(f"patch is {patch.size_bytes} bytes, over the {MAX_PATCH_BYTES}-byte limit")

    with tempfile.NamedTemporaryFile("w", suffix=".patch", delete=False, encoding="utf-8") as handle:
        # git apply is strict about the trailing newline on the last hunk.
        handle.write(patch.text if patch.text.endswith("\n") else patch.text + "\n")
        patch_path = handle.name

    try:
        argv = ["git", "-C", str(dest_dir), "apply", "--whitespace=nowarn", "-p1", patch_path]
        check = subprocess.run([*argv[:-1], "--check", patch_path], capture_output=True)
        if check.returncode != 0:
            raise PatchError(
                f"patch does not apply to the clean checkout: "
                f"{check.stderr.decode('utf-8', 'replace').strip()[:600]}"
            )
        result = subprocess.run(argv, capture_output=True)
        if result.returncode != 0:
            raise PatchError(
                f"git apply failed: {result.stderr.decode('utf-8', 'replace').strip()[:600]}"
            )
    finally:
        Path(patch_path).unlink(missing_ok=True)


def load_patch(path: Path) -> Patch:
    return Patch.from_text(Path(path).read_text(encoding="utf-8"))
